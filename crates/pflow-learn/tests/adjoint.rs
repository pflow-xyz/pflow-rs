#[test]
fn adjoint_observation_beyond_tf_still_contributes_loss_and_gradient() {
    // A point past tf jumps at the start of the backward pass rather than being dropped.
    let theta_true = 0.7;
    let theta = 0.5;
    let data = dataset_from(&decay_problem(theta_true), vec![0.5, 1.0, 1.5, 2.5], &["A"]);

    let prob = decay_problem(theta); // tspan = [0, 2], so t=2.5 is past tf

    let sens = solve_with_sensitivities(&prob, &methods::tsit5(), &solve_opts()).unwrap();
    let (fwd_loss, fwd_grad) = mse_loss_grad(&sens, &data);

    let adj = mse_loss_adjoint(&prob, &data, &methods::tsit5(), &solve_opts()).unwrap();

    assert_close("loss", adj.loss, fwd_loss, 1e-9, 1e-6);
    for (i, (&a, &f)) in adj.grad.iter().zip(fwd_grad.iter()).enumerate() {
        assert_close(&format!("grad[{i}]"), a, f, 1e-6, 1e-4);
    }
}

#[test]
fn adjoint_rejects_zero_params() {
    let net = PetriNet::build()
        .place("A", 1.0)
        .place("B", 0.0)
        .transition("t1")
        .arc("A", "t1", 1.0)
        .arc("t1", "B", 1.0)
        .done();
    let u0: State = [("A".to_string(), 1.0), ("B".to_string(), 0.0)]
        .into_iter()
        .collect();
    let prob = LearnableProblem::new(net, u0, [0.0, 1.0]); // no rate function installed

    let mut observations = HashMap::new();
    observations.insert("A".to_string(), vec![1.0]);
    let data = Dataset::new(vec![0.5], observations, vec!["A".to_string()]).unwrap();

    match mse_loss_adjoint(&prob, &data, &methods::tsit5(), &solve_opts()) {
        Err(LearnError::ZeroParams) => {}
        Err(other) => panic!("expected LearnError::ZeroParams, got {other:?}"),
        Ok(_) => panic!("expected an error, got a solve"),
    }
}

/// Central-differences `MSELoss(plain_solve(theta))` w.r.t. the decay problem's one
/// parameter, by rebuilding the `LearnableProblem` at theta +/- h and re-solving from
/// scratch — go-pflow's `fdFullSolveGrad`, not a cross-check against another Rust
/// derivation.
fn fd_dloss_dtheta_decay(
    theta: f64,
    data: &Dataset,
    loss_fn: impl Fn(&pflow_solver::ode::Solution, &Dataset) -> f64,
) -> f64 {
    let h = 1e-6 * (1.0 + theta.abs());

    let plus = decay_problem(theta + h);
    let loss_plus = loss_fn(&plus.solve(&methods::tsit5(), &solve_opts()).unwrap(), data);

    let minus = decay_problem(theta - h);
    let loss_minus = loss_fn(
        &minus.solve(&methods::tsit5(), &solve_opts()).unwrap(),
        data,
    );

    (loss_plus - loss_minus) / (2.0 * h)
}

/// Same as `fd_dloss_dtheta_decay`, but perturbs one of the two independent parameters
/// of `bimolecular_problem` (`param == 0` perturbs theta1, `param == 1` perturbs theta2).
fn fd_dloss_dtheta_bimolecular(
    theta1: f64,
    theta2: f64,
    param: usize,
    data: &Dataset,
    loss_fn: impl Fn(&pflow_solver::ode::Solution, &Dataset) -> f64,
) -> f64 {
    let (base, h) = if param == 0 {
        (theta1, 1e-6 * (1.0 + theta1.abs()))
    } else {
        (theta2, 1e-6 * (1.0 + theta2.abs()))
    };

    let (t1p, t2p) = if param == 0 {
        (base + h, theta2)
    } else {
        (theta1, base + h)
    };
    let plus = bimolecular_problem(t1p, t2p);
    let loss_plus = loss_fn(&plus.solve(&methods::tsit5(), &solve_opts()).unwrap(), data);

    let (t1m, t2m) = if param == 0 {
        (base - h, theta2)
    } else {
        (theta1, base - h)
    };
    let minus = bimolecular_problem(t1m, t2m);
    let loss_minus = loss_fn(
        &minus.solve(&methods::tsit5(), &solve_opts()).unwrap(),
        data,
    );

    (loss_plus - loss_minus) / (2.0 * h)
}

#[test]
fn adjoint_matches_direct_fd_single_param_mse() {
    let theta_true = 0.7;
    let theta = 0.5;
    let data = dataset_from(
        &decay_problem(theta_true),
        vec![0.25, 0.6, 1.1, 1.7],
        &["A", "B"],
    );

    let prob = decay_problem(theta);
    let adj = mse_loss_adjoint(&prob, &data, &methods::tsit5(), &solve_opts()).unwrap();

    let fd_loss_grad = fd_dloss_dtheta_decay(theta, &data, mse_loss);
    assert_close(
        "adjoint grad[0] vs direct FD",
        adj.grad[0],
        fd_loss_grad,
        1e-6,
        1e-3,
    );

    // The loss itself must also match a plain re-solve at theta (not just the FD slope).
    let sol = prob.solve(&methods::tsit5(), &solve_opts()).unwrap();
    assert_close(
        "adjoint loss vs plain-solve mse_loss",
        adj.loss,
        mse_loss(&sol, &data),
        1e-9,
        1e-6,
    );
}

