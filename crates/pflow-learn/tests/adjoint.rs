#[test]
fn adjoint_matches_direct_fd_two_params() {
    let data = dataset_from(
        &bimolecular_problem(0.6, 0.9),
        vec![0.1, 0.3, 0.55, 0.8],
        &["A", "B", "C", "D"],
    );

    let (theta1, theta2) = (0.4, 1.2);
    let prob = bimolecular_problem(theta1, theta2);
    let adj = mse_loss_adjoint(&prob, &data, &methods::tsit5(), &solve_opts()).unwrap();

    for param in 0..2 {
        let fd = fd_dloss_dtheta_bimolecular(theta1, theta2, param, &data, mse_loss);
        assert_close(
            &format!("adjoint grad[{param}] vs direct FD"),
            adj.grad[param],
            fd,
            1e-6,
            1e-3,
        );
    }

    let sol = prob.solve(&methods::tsit5(), &solve_opts()).unwrap();
    assert_close(
        "adjoint loss vs plain-solve mse_loss",
        adj.loss,
        mse_loss(&sol, &data),
        1e-9,
        1e-6,
    );
}
