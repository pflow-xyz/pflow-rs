    fn chain_reference_trace_spec_3_8() {
        // First step of realization 0 (seed 42) reproduces the spec's trace.
        let compiled = compile(&chain()).unwrap();
        let mut props = Vec::new();
        let marking = compiled.initial_marking().to_vec();
        let a0 = compiled.propensities(&marking, &mut props);
        assert_eq!(a0, 100.0);
        let mut g = Xoshiro256::new(42);
        let x1 = g.uniform();
        let u = 1.0 - x1;
        assert_eq!(u.to_bits(), 0x3FED_50FE_9A3E_7A28);
        let dt = (-plog(u)) / a0;
        assert_eq!(dt.to_bits(), 0x3F4C_B386_8D3A_58D8);
        let x2 = g.uniform();
        assert_eq!(x2 * a0, 37.89802506626686);
        // step 2 dt
        let x1 = g.uniform();
        let u = 1.0 - x1;
        assert_eq!(u, 0.31995658897186063);
        assert_eq!(((-plog(u)) / a0).to_bits(), 0x3F87_56A0_E5FA_32AF);
    }

