    #[test]
    fn gating_semantics() {
        // Capacity: fill is blocked when p + 1 > 2. Inhibitor: blocked while g >= 1.
        // Read: drain requires g >= 1 but does not consume it.
        let model = SsaModel {
            places: vec![
                SsaPlace {
                    id: "p".into(),
                    initial: 2,
                    capacity: 2,
                },
                SsaPlace {
                    id: "g".into(),
                    initial: 1,
                    capacity: 0,
                },
                SsaPlace {
                    id: "q".into(),
                    initial: 0,
                    capacity: 0,
                },
            ],
            transitions: vec![
                SsaTransition {
                    id: "fill".into(),
                    rate: 1.0,
                    delay: 0.0,
                },
                SsaTransition {
                    id: "blocked".into(),
                    rate: 1.0,
                    delay: 0.0,
                },
                SsaTransition {
                    id: "drain".into(),
                    rate: 1.0,
                    delay: 0.0,
                },
                SsaTransition {
                    id: "nonkin".into(),
                    rate: 1.0,
                    delay: 0.0,
                },
            ],
            arcs: vec![
                SsaArc::flow("fill", "p"),
                SsaArc {
                    from: "g".into(),
                    to: "blocked".into(),
                    weight: 1,
                    kind: ArcKind::Inhibitor,
                    kinetic: true,
                },
                SsaArc::flow("blocked", "q"),
                SsaArc {
                    from: "g".into(),
                    to: "drain".into(),
                    weight: 1,
                    kind: ArcKind::Read,
                    kinetic: true,
                },
                SsaArc::flow("p", "drain"),
                SsaArc::flow("drain", "q"),
                SsaArc {
                    from: "p".into(),
                    to: "nonkin".into(),
                    weight: 2,
                    kind: ArcKind::Flow,
                    kinetic: false,
                },
            ],
        };
        let compiled = compile(&model).unwrap();
        let mut props = Vec::new();
        let a0 = compiled.propensities(&[2, 1, 0], &mut props);
        // fill blocked by capacity, blocked inhibited, drain = 1*C(2,1) = 2, nonkin = 1 (no product).
        assert_eq!(props, vec![0.0, 0.0, 2.0, 1.0]);
        assert_eq!(a0, 3.0);
        let a0 = compiled.propensities(&[1, 0, 0], &mut props);
        // fill admitted (1+1 <= 2), blocked admitted (g < 1), drain gated by read, nonkin m<w.
        assert_eq!(props, vec![1.0, 1.0, 0.0, 0.0]);
        assert_eq!(a0, 2.0);
    }

    #[test]
    fn compile_rejects_bad_models() {
        let mut m = chain();
        m.arcs.push(SsaArc::flow("a", "zzz"));
        assert!(matches!(
            compile(&m),
            Err(SsaError::UnknownEndpoint { arc: 4, .. })
        ));
        let mut m = chain();
        m.arcs.push(SsaArc {
            from: "ab".into(),
            to: "b".into(),
            weight: 1,
            kind: ArcKind::Read,
            kinetic: true,
        });
        assert!(matches!(
            compile(&m),
            Err(SsaError::ReadOrInhibitorFromTransition { arc: 4 })
        ));
        let mut m = chain();
        m.arcs.push(SsaArc::flow("a", "b"));
        assert!(matches!(
            compile(&m),
            Err(SsaError::ArcBetweenSameKind { arc: 4 })
        ));
        let mut m = chain();
        m.places[1].id = "a".into();
        assert!(matches!(compile(&m), Err(SsaError::DuplicateId(_))));
        assert!(matches!(
            simulate(
                &chain(),
                &SsaOptions {
                    samples: 1,
                    ..SsaOptions::default()
                }
            ),
            Err(SsaError::BadOptions(_))
        ));
    }

    #[test]
    fn from_petri_net_roundtrip() {
        let mut net = pflow_core::PetriNet::new();
        net.add_place("a", vec![100.0], vec![], 0.0, 0.0, None);
        net.add_place("b", vec![0.0], vec![], 0.0, 0.0, None);
        net.add_place("c", vec![0.0], vec![], 0.0, 0.0, None);
        net.add_transition("ab", "", 0.0, 0.0, None);
        net.add_transition("bc", "", 0.0, 0.0, None);
        net.add_arc("a", "ab", vec![1.0], false);
        net.add_arc("ab", "b", vec![1.0], false);
        net.add_arc("b", "bc", vec![1.0], false);
        net.add_arc("bc", "c", vec![1.0], false);
        let order_p: Vec<String> = ["a", "b", "c"].iter().map(|s| s.to_string()).collect();
        let order_t: Vec<String> = ["ab", "bc"].iter().map(|s| s.to_string()).collect();
        let rates: HashMap<String, f64> = [("ab".to_string(), 1.0), ("bc".to_string(), 1.0)]
            .into_iter()
            .collect();
        let m = SsaModel::from_petri_net(&net, &order_p, &order_t, &rates).unwrap();
        assert_eq!(m, chain());
        let o = SsaOptions {
            horizon: 10.0,
            samples: 11,
            realizations: 3,
            seed: 42,
        };
        assert_eq!(simulate(&m, &o).unwrap(), simulate(&chain(), &o).unwrap());
    }
