//! Portable, correctly rounded `pow`.
//!
//! `f64::powf` is the platform libm's `pow`: Apple's on macOS, glibc's on
//! Linux, and on wasm32 Rust's own port of musl's. None is correctly rounded
//! (measured on controller-sized inputs: 0.135 % of calls wrong on macOS /
//! arm64, 0.063 % on glibc, more on wasm32), and they are wrong on different
//! inputs, so the ODE step controller's `(1/err)^(1/(order+1))` rounded
//! differently on each host. One ulp in one step moves every later step, the
//! final state, and in a game search the order of moves whose guesses tie.
//!
//! [`pow`] returns `x^y` rounded once to the nearest double (ties to even) on
//! every input, using nothing but IEEE 754 `+ - * /`, comparisons, integer
//! arithmetic and bit casts, so it is the same function on every host:
//! native, wasm32, and its ports in go-pflow (`crmath/pow.go`), pflow-xyz
//! (`internal/crmath`, `public/petri-crmath.js`). The ports are operation for
//! operation the same; `tests/crmath_corpus.rs` and its copies hold all of
//! them to one corpus of `(x, y, x^y)` bit patterns computed with Python's
//! `decimal` at 120 digits (`scripts/crmath/corpus.py`).
//!
//! How:
//!
//! 1. Fast path, double-double (about 106 bits). `x = m 2^e` with
//!    `m` in `[sqrt(2)/2, sqrt(2))`; `ln m = 2 atanh(s)`, `s = (m-1)/(m+1)`,
//!    by its series in `s^2`; `ln x = ln m + e ln 2`; `t = y ln x`;
//!    `exp(t) = 2^k exp(r)` with `r = t - k ln 2` and `exp(r)` by its Taylor
//!    series. Relative error below 2^-90 over the whole range.
//! 2. Ziv's rounding test: if the double-double result `hi + lo` is farther
//!    than 2^-74 (relative) from a rounding boundary, `hi` is the correctly
//!    rounded result. Otherwise (about one call in a million, and every exact
//!    midpoint such as `(1 + 2^-27)^2`), and for results near overflow or in
//!    the subnormal range:
//! 3. Slow path, 320-bit fixed point: the same formulas in integer
//!    arithmetic, error below 2^-300, rounded directly to a double (subnormals
//!    included). A remainder within 2^-250 of a midpoint is taken to be the
//!    midpoint, which is what an exact midpoint computes to.
//!
//! Every product is written so that no compiler fuses it with an add (Rust
//! never contracts; the Go port wraps each product in `float64(...)`).
//! Special cases (zeros, infinities, NaN, negative bases) are C99 Annex F's.

/// `hi + lo`, `|lo| <= ulp(hi) / 2`.
#[derive(Clone, Copy, Debug)]
struct Dd {
    hi: f64,
    lo: f64,
}

impl Dd {
    const fn new(hi: f64, lo: f64) -> Dd {
        Dd { hi, lo }
    }
}

