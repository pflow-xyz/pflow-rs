const SQRT2_OVER_2: f64 = f64::from_bits(0x3FE6A09E667F3BCD);
/// 2^27 + 1, Veltkamp's splitter.
const SPLITTER: f64 = 134217729.0;
const TWO53: f64 = 9007199254740992.0;
const TWO63: f64 = 9223372036854775808.0;
/// 1 + 2^-20: Ziv's rounding test (see the module doc).
const ROUND: f64 = f64::from_bits(0x3FF0000100000000);

/// `x^y`, correctly rounded, the same bits on every host.
pub fn pow(x: f64, y: f64) -> f64 {
    if y == 0.0 || x == 1.0 {
        return 1.0;
    }
    if x.is_nan() || y.is_nan() {
        return f64::NAN;
    }
    let yc = y_class(y);
    if y.is_infinite() {
        let ax = x.abs();
        if ax == 1.0 {
            return 1.0;
        }
        return if (ax < 1.0) == (y > 0.0) {
            0.0
        } else {
            f64::INFINITY
        };
    }
    if x == 0.0 {
        let odd = yc == YClass::Odd;
        return if y < 0.0 {
            if odd {
                1.0 / x
            } else {
                f64::INFINITY
            }
        } else if odd {
            x
        } else {
            0.0
        };
    }
    if x.is_infinite() {
        let odd = yc == YClass::Odd;
        if x > 0.0 {
            return if y < 0.0 { 0.0 } else { f64::INFINITY };
        }
        return if y < 0.0 {
            if odd {
                -0.0
            } else {
                0.0
            }
        } else if odd {
            f64::NEG_INFINITY
        } else {
            f64::INFINITY
        };
    }
    if x < 0.0 {
        return match yc {
            YClass::NotInteger => f64::NAN,
            YClass::Odd => -pow_pos(-x, y),
            YClass::Even => pow_pos(-x, y),
        };
    }
    pow_pos(x, y)
}

#[derive(PartialEq, Eq)]
enum YClass {
    NotInteger,
    Odd,
    Even,
}

/// Whether finite or infinite `y` is an odd integer, an even one, or neither.
fn y_class(y: f64) -> YClass {
    let ay = y.abs();
    if ay >= TWO53 {
        return YClass::Even;
    }
    let t = y.trunc();
    if t != y {
        return YClass::NotInteger;
    }
    if (t as i64) & 1 == 1 {
        YClass::Odd
    } else {
        YClass::Even
    }
}

/// `x^y` for finite `x > 0` and finite `y != 0`.
fn pow_pos(x: f64, y: f64) -> f64 {
    if x == 1.0 {
        return 1.0;
    }
    let (m, e) = reduce(x);
    // |y ln x| > 1024 for every double x != 1 once |y| >= 2^63.
    if y.abs() >= TWO63 {
        return if (x > 1.0) == (y > 0.0) {
            f64::INFINITY
        } else {
            0.0
        };
    }
    let t = dd_mul_f(ln_dd(m, e), y);
    if t.hi > 709.79 {
        return f64::INFINITY;
    }
    if t.hi < -745.2 {
        return 0.0;
    }
    if t.hi > -708.0 && t.hi < 709.0 {
        let (p, k) = exp_dd(t);
        if p.hi == p.hi + p.lo * ROUND {
            return p.hi * two_pow(k);
        }
    }
    slow(m, e, y, t.hi)
}

/// `x = m 2^e`, `m` in `[sqrt(2)/2, sqrt(2))`, for finite `x > 0`.
fn reduce(x: f64) -> (f64, i32) {
    let mut x = x;
    let mut b = x.to_bits();
    let mut ex = ((b >> 52) & 0x7FF) as i32;
    if ex == 0 {
        // Subnormal: multiplying by 2^52 is exact.
        x *= f64::from_bits(0x4330_0000_0000_0000);
        b = x.to_bits();
        ex = ((b >> 52) & 0x7FF) as i32 - 52;
    }
    let mut e = ex - 1022;
    let mut m = f64::from_bits((b & !(0x7FFu64 << 52)) | (1022u64 << 52));
    if m < SQRT2_OVER_2 {
        m *= 2.0;
        e -= 1;
    }
    (m, e)
}

/// `2^k`, `-1022 <= k <= 1023`.
fn two_pow(k: i32) -> f64 {
    f64::from_bits(((k + 1023) as u64) << 52)
}

/// The integer nearest `q` (half away from zero), `|q| < 2^31`.
fn nearest(q: f64) -> i32 {
    if q >= 0.0 {
        (q + 0.5) as i32
    } else {
        -((0.5 - q) as i32)
    }
}

fn two_sum(a: f64, b: f64) -> (f64, f64) {
    let s = a + b;
    let bb = s - a;
    let e = (a - (s - bb)) + (b - bb);
    (s, e)
}

fn quick_two_sum(a: f64, b: f64) -> (f64, f64) {
    let s = a + b;
    let e = b - (s - a);
    (s, e)
}

fn split(a: f64) -> (f64, f64) {
    let t = SPLITTER * a;
    let hi = t - (t - a);
    let lo = a - hi;
    (hi, lo)
}

/// `a * b` exactly, as `p + e` (Dekker; no FMA, which wasm32 lacks).
fn two_prod(a: f64, b: f64) -> (f64, f64) {
    let p = a * b;
    let (ah, al) = split(a);
    let (bh, bl) = split(b);
    let e = ((ah * bh - p) + ah * bl + al * bh) + al * bl;
    (p, e)
}

fn dd_add(x: Dd, y: Dd) -> Dd {
    let (s, e) = two_sum(x.hi, y.hi);
    let (t, f) = two_sum(x.lo, y.lo);
    let e = e + t;
    let (s, e) = quick_two_sum(s, e);
    let e = e + f;
    let (s, e) = quick_two_sum(s, e);
    Dd::new(s, e)
}

fn dd_neg(x: Dd) -> Dd {
    Dd::new(-x.hi, -x.lo)
}

fn dd_mul(x: Dd, y: Dd) -> Dd {
    let (p, e) = two_prod(x.hi, y.hi);
    let e = e + (x.hi * y.lo + x.lo * y.hi);
    let (p, e) = quick_two_sum(p, e);
    Dd::new(p, e)
}

fn dd_mul_f(x: Dd, f: f64) -> Dd {
    let (p, e) = two_prod(x.hi, f);
    let e = e + x.lo * f;
    let (p, e) = quick_two_sum(p, e);
    Dd::new(p, e)
}

fn dd_div(a: Dd, b: Dd) -> Dd {
    let q1 = a.hi / b.hi;
    let r = dd_add(a, dd_neg(dd_mul_f(b, q1)));
    let q2 = r.hi / b.hi;
    let r = dd_add(r, dd_neg(dd_mul_f(b, q2)));
    let q3 = r.hi / b.hi;
    let (q1, q2) = quick_two_sum(q1, q2);
    dd_add(Dd::new(q1, q2), Dd::new(q3, 0.0))
}

/// `ln(m 2^e)` in double-double.
fn ln_dd(m: f64, e: i32) -> Dd {
    // m - 1 is exact (Sterbenz).
    let f = m - 1.0;
    let (dh, dl) = two_sum(2.0, f);
    let s = dd_div(Dd::new(f, 0.0), Dd::new(dh, dl));
    let s2 = dd_mul(s, s);
    let mut p = INV_ODD[INV_ODD.len() - 1];
    for k in (0..INV_ODD.len() - 1).rev() {
        p = dd_add(dd_mul(p, s2), INV_ODD[k]);
    }
    let lm = dd_mul(s, p);
    let lm = Dd::new(2.0 * lm.hi, 2.0 * lm.lo);
    // e ln 2: e * LN2_1 is exact (LN2_1 has 32 significant bits, |e| < 2^11).
    let fe = e as f64;
    let (p2, pe2) = two_prod(fe, LN2_2);
    let (h, l) = two_sum(fe * LN2_1, p2);
    let l = l + (pe2 + fe * LN2_3);
    let (h, l) = quick_two_sum(h, l);
    dd_add(Dd::new(h, l), lm)
}

/// `exp(t) = p 2^k`, for `|t.hi| < 709`.
fn exp_dd(t: Dd) -> (Dd, i32) {
    let k = nearest(t.hi * INV_LN2);
    let fk = k as f64;
    let (h, l) = two_sum(t.hi, -(fk * LN2_1));
    let r = dd_add(Dd::new(h, l), Dd::new(t.lo, 0.0));
    let (p, pe) = two_prod(fk, LN2_2);
    let r = dd_add(r, Dd::new(-p, -pe));
    let r = dd_add(r, Dd::new(-(fk * LN2_3), 0.0));
    let mut s = INV_FACT[INV_FACT.len() - 1];
    for n in (0..INV_FACT.len() - 1).rev() {
        s = dd_add(dd_mul(s, r), INV_FACT[n]);
    }
    (s, k)
}

// The slow path.

/// Unsigned fixed point: `sum(limb[i] 2^(64 i)) / 2^320`, low limb first;
/// five fractional limbs and one integer limb.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
struct Fx([u64; 6]);

impl Fx {
    const ZERO: Fx = Fx([0; 6]);

    fn int(n: u64) -> Fx {
        Fx([0, 0, 0, 0, 0, n])
    }

    /// `2^(n - 320)`, `n < 384`.
    fn bit(n: u32) -> Fx {
        let mut r = Fx::ZERO;
        r.0[(n / 64) as usize] = 1u64 << (n % 64);
        r
    }

    fn is_zero(&self) -> bool {
        self.0.iter().all(|&l| l == 0)
    }

    fn less(&self, o: &Fx) -> bool {
        for i in (0..6).rev() {
            if self.0[i] != o.0[i] {
                return self.0[i] < o.0[i];
            }
        }
        false
    }

    fn add(&self, o: &Fx) -> Fx {
        let mut r = Fx::ZERO;
        let mut c = 0u64;
        for i in 0..6 {
            let (s1, c1) = self.0[i].overflowing_add(o.0[i]);
            let (s2, c2) = s1.overflowing_add(c);
            r.0[i] = s2;
            c = (c1 as u64) + (c2 as u64);
        }
        r
    }

    /// `self - o`, `o <= self`.
    fn sub(&self, o: &Fx) -> Fx {
        let mut r = Fx::ZERO;
        let mut b = 0u64;
        for i in 0..6 {
            let (d1, b1) = self.0[i].overflowing_sub(o.0[i]);
            let (d2, b2) = d1.overflowing_sub(b);
            r.0[i] = d2;
            b = (b1 as u64) + (b2 as u64);
        }
        r
    }

    /// `self * o`, truncated; the product must be below 2^64.
    fn mul(&self, o: &Fx) -> Fx {
        let mut w = [0u64; 12];
        for i in 0..6 {
            let mut c: u128 = 0;
            for j in 0..6 {
                let cur = (self.0[i] as u128) * (o.0[j] as u128) + (w[i + j] as u128) + c;
                w[i + j] = cur as u64;
                c = cur >> 64;
            }
            w[i + 6] = c as u64;
        }
        Fx([w[5], w[6], w[7], w[8], w[9], w[10]])
    }

    /// `self * n`; the product must be below 2^64.
    fn mul_small(&self, n: u64) -> Fx {
        let mut r = Fx::ZERO;
        let mut c: u128 = 0;
        for i in 0..6 {
            let cur = (self.0[i] as u128) * (n as u128) + c;
            r.0[i] = cur as u64;
            c = cur >> 64;
        }
        r
    }

    /// `self / d`, truncated, `d > 0`.
    fn div_small(&self, d: u64) -> Fx {
        let mut r = Fx::ZERO;
        let mut rem: u128 = 0;
        for i in (0..6).rev() {
            let cur = (rem << 64) | (self.0[i] as u128);
            r.0[i] = (cur / (d as u128)) as u64;
            rem = cur % (d as u128);
        }
        r
    }

    fn shl(&self, n: u32) -> Fx {
        let mut r = Fx::ZERO;
        let (w, b) = ((n / 64) as usize, n % 64);
        for i in (0..6).rev() {
            if i < w {
                break;
            }
            let mut v = self.0[i - w] << b;
            if b > 0 && i > w {
                v |= self.0[i - w - 1] >> (64 - b);
            }
            r.0[i] = v;
        }
        r
    }

    fn shr(&self, n: u32) -> Fx {
        let mut r = Fx::ZERO;
        let (w, b) = ((n / 64) as usize, n % 64);
        for i in 0..6 {
            if i + w >= 6 {
                break;
            }
            let mut v = self.0[i + w] >> b;
            if b > 0 && i + w + 1 < 6 {
                v |= self.0[i + w + 1] << (64 - b);
            }
            r.0[i] = v;
        }
        r
    }

    /// The low `n` bits, `n < 384`.
    fn low(&self, n: u32) -> Fx {
        let mut r = *self;
        let (w, b) = ((n / 64) as usize, n % 64);
        for i in 0..6 {
            if i > w || (i == w && b == 0) {
                r.0[i] = 0;
            } else if i == w {
                r.0[i] &= (1u64 << b) - 1;
            }
        }
        r
    }
}

/// `(an ? -a : a) + (bn ? -b : b)` as a sign and a magnitude; zero is
/// positive.
fn signed_add(an: bool, a: Fx, bn: bool, b: Fx) -> (bool, Fx) {
    if an == bn {
        let s = a.add(&b);
        return (an && !s.is_zero(), s);
    }
    if b.less(&a) {
        (an, a.sub(&b))
    } else {
        let d = b.sub(&a);
        (bn && !d.is_zero(), d)
    }
}

/// `x^y` from `x = m 2^e` in 320-bit fixed point, rounded once. `t_hi`
/// approximates `y ln x`, which is within `[-745.2, 709.79]`.
fn slow(m: f64, e: i32, y: f64, t_hi: f64) -> f64 {
    // m 2^53 is an integer below 2^54.
    let big_m = (m * TWO53) as u64;
    let h = 1u64 << 53;
    let (s_neg, num) = if big_m < h {
        (true, h - big_m)
    } else {
        (false, big_m - h)
    };
    // s = (m - 1) / (m + 1); ln m = 2 atanh(s).
    let s = Fx::int(num).div_small(big_m + h);
    let s2 = s.mul(&s);
    let mut term = s;
    let mut sum = s;
    let mut k = 1u64;
    loop {
        term = term.mul(&s2);
        if term.is_zero() {
            break;
        }
        sum = sum.add(&term.div_small(2 * k + 1));
        k += 1;
    }
    let lnm = sum.shl(1);
    let (l_neg, l) = signed_add(s_neg, lnm, e < 0, LN2_FX.mul_small(e.unsigned_abs() as u64));
    // t = y ln x, y = ym 2^ye.
    let yb = y.to_bits();
    let y_neg = (yb >> 63) == 1;
    let yexp = ((yb >> 52) & 0x7FF) as i32;
    let (ym, ye) = if yexp == 0 {
        (yb & ((1u64 << 52) - 1), -1074)
    } else {
        ((yb & ((1u64 << 52) - 1)) | (1u64 << 52), yexp - 1075)
    };
    let tm = l.mul_small(ym);
    let tm = if ye >= 0 {
        tm.shl(ye as u32)
    } else if ye > -384 {
        tm.shr((-ye) as u32)
    } else {
        Fx::ZERO
    };
    let t_neg = l_neg != y_neg && !tm.is_zero();
    // r = t - k ln 2 in [0, ln 2).
    let mut k = nearest(t_hi * INV_LN2) as i64;
    let (mut r_neg, mut r) = signed_add(t_neg, tm, k > 0, LN2_FX.mul_small(k.unsigned_abs()));
    while r_neg {
        k -= 1;
        let (n, v) = signed_add(r_neg, r, false, LN2_FX);
        r_neg = n;
        r = v;
    }
    while !r.less(&LN2_FX) {
        k += 1;
        r = r.sub(&LN2_FX);
    }
    // exp(r) in [1, 2).
    let mut sum = Fx::int(1);
    let mut term = sum;
    let mut n = 1u64;
    loop {
        term = term.mul(&r).div_small(n);
        if term.is_zero() {
            break;
        }
        sum = sum.add(&term);
        n += 1;
    }
    round_scaled(sum, k)
}

/// `sum 2^k` rounded to the nearest double, ties to even, `sum` in `[1, 2)`.
fn round_scaled(sum: Fx, k: i64) -> f64 {
    let (sum, k) = if sum.0[5] >= 2 {
        (sum.shr(1), k + 1)
    } else {
        (sum, k)
    };
    // Bits kept below the leading one.
    let p: i64 = if k >= -1022 { 52 } else { 52 - (-1022 - k) };
    if p < -1 {
        return 0.0;
    }
    let shift = (320 - p) as u32;
    let mut mant = sum.shr(shift).0[0];
    let rem = sum.low(shift);
    let half = Fx::bit(shift - 1);
    let tol = Fx::bit(70);
    let up = if half.add(&tol).less(&rem) {
        true
    } else if rem.add(&tol).less(&half) {
        false
    } else {
        mant & 1 == 1
    };
    if up {
        mant += 1;
    }
    let mut ex = k - p;
    if mant == 1u64 << 53 {
        mant >>= 1;
        ex += 1;
    }
    if mant >= 1u64 << 52 {
        let biased = ex + 52 + 1023;
        if biased >= 2047 {
            return f64::INFINITY;
        }
        return f64::from_bits(((biased as u64) << 52) | (mant - (1u64 << 52)));
    }
    f64::from_bits(mant)
}

/// The slow path alone, for tests: it must agree with [`pow`] everywhere.
#[doc(hidden)]
pub fn pow_slow(x: f64, y: f64) -> f64 {
    let (m, e) = reduce(x);
    let t = dd_mul_f(ln_dd(m, e), y);
    slow(m, e, y, t.hi)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exact_and_special() {
        assert_eq!(pow(2.0, 10.0), 1024.0);
        assert_eq!(pow(4.0, 0.5), 2.0);
        assert_eq!(pow(10.0, -2.0), 0.01);
        assert_eq!(pow(-2.0, 3.0), -8.0);
        assert!(pow(-2.0, 0.5).is_nan());
        assert_eq!(pow(0.0, -1.0), f64::INFINITY);
        assert_eq!(pow(-0.0, -1.0), f64::NEG_INFINITY);
        assert_eq!(pow(f64::NAN, 0.0), 1.0);
        assert_eq!(pow(1.0, f64::NAN), 1.0);
        assert_eq!(pow(-1.0, f64::INFINITY), 1.0);
        assert_eq!(pow(2.0, 1024.0), f64::INFINITY);
        assert_eq!(pow(2.0, -1074.0), f64::from_bits(1));
        assert_eq!(pow(2.0, -1075.0), 0.0);
        assert_eq!(pow(2.0, -1022.5).to_bits(), 3184525836262886);
        // An exact midpoint: 1 + 2^-26 + 2^-54 rounds to even.
        let x = 1.0 + 2f64.powi(-27);
        assert_eq!(pow(x, 2.0), 1.0 + 2f64.powi(-26));
    }

    #[test]
    fn slow_agrees_with_fast() {
        let mut s = 0x9E37_79B9_7F4A_7C15u64;
        let mut next = || {
            s ^= s << 13;
            s ^= s >> 7;
            s ^= s << 17;
            s
        };
        for _ in 0..20000 {
            let x = f64::from_bits(next() % 0x7FF0_0000_0000_0000);
            let y = (next() as f64 / u64::MAX as f64) * 8.0 - 4.0;
            if x.is_nan() || x <= 0.0 {
                continue;
            }
            let (a, b) = (pow(x, y), pow_slow(x, y));
            assert_eq!(
                a.to_bits(),
                b.to_bits(),
                "pow({x:e}, {y:e}): fast {a:e}, slow {b:e}"
            );
        }
    }
}
